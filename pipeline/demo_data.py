def elem_schools_geojson():
    feats = []
    for name, lat, lng, poly in ELEM_SCHOOLS:
        ring = poly + [poly[0]]
        feats.append({"type": "Feature", "properties": {"name": name, "kind": "zone"},
                      "geometry": {"type": "Polygon", "coordinates": [ring]}})
        feats.append({"type": "Feature", "properties": {"name": name, "kind": "school"},
                      "geometry": {"type": "Point", "coordinates": [lng, lat]}})
    return {"type": "FeatureCollection", "features": feats}


