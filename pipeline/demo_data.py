def gen_trades(cid, base_ppy, areas, built, seed):
    """최근 24개월 실거래 생성. 평당가 기준 완만한 상승 + 노이즈."""
    rnd = random.Random(seed)
    rows = []
    today = dt.date.today()
    for mi in range(24, -1, -1):
        y, m = today.year, today.month - mi
        while m <= 0:
            y -= 1
            m += 12
        trend = 1.0 - 0.006 * mi + rnd.uniform(-0.015, 0.015)   # 월 0.6% 상승 흉내
        n = rnd.choice([0, 1, 1, 2, 2, 3])
        for _ in range(n):
            area = rnd.choice(areas)
            py = area / 3.3058
            floor = rnd.randint(2, 25)
            fl_adj = 1.0 + (floor - 12) * 0.004
            ppy = base_ppy * trend * fl_adj * rnd.uniform(0.97, 1.03)
            rows.append({
                "date": "{:04d}-{:02d}-{:02d}".format(y, m, rnd.randint(1, 28)),
                "area": area,
                "floor": floor,
                "price": int(round(ppy * py / 100.0)) * 100,   # 만원, 백만원 단위 반올림
                "kind": "중개거래",
            })
    rows.sort(key=lambda r: r["date"])
    return rows


